function epOpenWeatherRegionalIcon(key) {
    const japanese = key.split(/(のち|後|時々|時どき|一時)/);
    const korean = key.split(/_(후|이후|때때로|가끔|한때)_/);
    const useKorean = korean.length > 1 || Object.hasOwn(epOpenWeatherKoreanIcons, key);
    const [first, connector, second] = useKorean ? korean : japanese;
    const icons = useKorean ? epOpenWeatherKoreanIcons : epOpenWeatherJapaneseIcons;
    if (!Object.hasOwn(icons, first)) return null;
    if (!connector) return icons[first];
    if ((useKorean ? korean.length : japanese.length) !== 3 || !Object.hasOwn(icons, second)) return null;
    const relation = /^(のち|後|후|이후)$/.test(connector) ? 'sequence'
        : /^(一時|한때)$/.test(connector) ? 'brief' : 'intermittent';
    return `${relation}:${icons[first]}:${icons[second]}`;
}

function epOpenWeatherForecastIcon(label, sourceIcon) {
    const key = label.normalize('NFKC').toUpperCase().replace(/[^\p{L}\p{N}]+/gu, '_').replace(/^_|_$/g, '')
        .replace(/(_BUT_LATER_TURNING_TO_(?:RAIN_AND_SNOW|SNOW_AND_RAIN))_WITH_(RAIN|SNOW)_AS_THE_MAIN_CONSTITUENT$/, '$1_MAIN_CONSTITUENT_$2')
        .replace(/_WITH_(RAIN|SNOW)_AS_THE_MAIN_CONSTITUENT$/, '_$1_AS_MAIN_CONSTITUENT')
        .replace(/^(RAIN|SNOW)_(SNOW|RAIN)_MIX_(.+)_AS_MAIN_CONSTITUENT$/, '$1$2_MIX_$3_AS_MAIN');
    const forecastIcon = Object.hasOwn(epOpenWeatherForecastTypes, key) ? epOpenWeatherForecastTypes[key]
        : Object.hasOwn(epOpenWeatherForecastAliases, key) ? epOpenWeatherForecastAliases[key] : epOpenWeatherRegionalIcon(key);

    // The icon can carry the time of day even if the label is unchanged.
    if (forecastIcon?.endsWith('-day') && sourceIcon === forecastIcon.replace(/-day$/, '-night')) return sourceIcon;
    if (forecastIcon === 'rain-showers' || forecastIcon === 'snow-showers') {
        if (sourceIcon === `${forecastIcon}-day` || sourceIcon === `${forecastIcon}-night`) return sourceIcon;
    }
    return forecastIcon ?? sourceIcon;
}
